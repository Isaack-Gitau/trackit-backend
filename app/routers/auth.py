"""
TRACKIT Authentication Router.

Authentication endpoints for:

- User registration
- User login
- Current-user information
- Email verification
- Resending verification tokens
- Forgot-password requests
- Password reset

Security principles:

- Strict Pydantic validation is applied before service logic.
- Passwords are never returned.
- Authentication failures use safe responses.
- Verification/reset requests do not reveal account existence.
- Raw authentication tokens are never stored in PostgreSQL.
- Authentication tokens are short-lived and single-use.
- JWT authentication is handled through API dependencies.
"""

from fastapi import APIRouter, Depends, HTTPException, status
from sqlalchemy.exc import IntegrityError
from sqlalchemy.orm import Session

from app.api.deps import get_current_user
from app.db.dependencies import get_db

from app.models.user import User

from app.schemas.auth import (
    AuthenticatedUserResponse,
    TokenResponse,
    UserLoginRequest,
    UserRegisterRequest,
)

from app.services.auth import (
    login_user,
    register_user,
)

from app.services.email_verification import (
    create_verification_token,
    verify_email,
)

from app.services.password_reset import (
    create_password_reset_token,
    reset_user_password,
)

from app.services.tokens import (
    EMAIL_VERIFICATION_TOKEN_TYPE,
    PASSWORD_RESET_TOKEN_TYPE,
    get_valid_token,
)

from app.services.user import (
    get_user_by_email_service,
)


# ============================================================================
# Router
# ============================================================================

router = APIRouter(
    prefix="/api/auth",
    tags=["Authentication"],
)


# ============================================================================
# Registration
# ============================================================================

@router.post(
    "/register",
    response_model=AuthenticatedUserResponse,
    status_code=status.HTTP_201_CREATED,
    summary="Register a new user",
)
def register(
    data: UserRegisterRequest,
    db: Session = Depends(get_db),
) -> AuthenticatedUserResponse:
    """
    Register a new TRACKIT user account.

    Newly registered users:

    - are active
    - are unverified
    - cannot log in until email verification
    - receive a short-lived verification token

    The raw verification token is generated by the
    email-verification service and is never stored.
    """

    try:
        user = register_user(
            db,
            username=data.username,
            first_name=data.first_name,
            last_name=data.last_name,
            email=str(data.email),
            password=data.password,
        )

    except ValueError as exc:
        raise HTTPException(
            status_code=status.HTTP_409_CONFLICT,
            detail=str(exc),
        ) from exc

    except IntegrityError:
        db.rollback()

        raise HTTPException(
            status_code=status.HTTP_409_CONFLICT,
            detail="Username or email is already registered.",
        ) from None

    # Create the verification token.

    create_verification_token(
        db,
        user,
    )

    return AuthenticatedUserResponse.model_validate(user)


# ============================================================================
# Login
# ============================================================================

@router.post(
    "/login",
    response_model=TokenResponse,
    summary="Authenticate a user",
)
def login(
    data: UserLoginRequest,
    db: Session = Depends(get_db),
) -> TokenResponse:
    """
    Authenticate a TRACKIT user.

    Login requires:

    - valid username or email
    - valid password
    - active account
    - verified email
    """

    result = login_user(
        db,
        login=data.identifier,
        password=data.password,
    )

    if result is None:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Invalid credentials or account not eligible for login.",
            headers={
                "WWW-Authenticate": "Bearer",
            },
        )

    access_token, _user = result

    return TokenResponse(
        access_token=access_token,
        token_type="bearer",
    )


