@router.post(
    "/forgot-password",
    summary="Request a password reset",
)
def forgot_password(
    email: str,
    db: Session = Depends(get_db),
) -> dict[str, str]:
    """
    Start the TRACKIT password-reset process.

    The response never reveals whether an account
    exists for the supplied email.
    """

    generic_message = (
        "If an account exists for this email, "
        "a password reset message has been sent."
    )

    user = get_user_by_email_service(
        db,
        email,
    )

    if user is None:
        return {
            "message": generic_message,
        }

    if not user.is_active:
        return {
            "message": generic_message,
        }

    create_password_reset_token(
        db,
        user,
    )

    return {
        "message": generic_message,
    }


# ============================================================================
# Password Reset
# ============================================================================

@router.post(
    "/reset-password",
    summary="Reset a user password",
)
def reset_password(
    token: str,
    new_password: str,
    db: Session = Depends(get_db),
) -> dict[str, str]:
    """
    Reset a user's password using a valid single-use
    password-reset token.

    Successful reset:

    - changes the password
    - updates password_changed_at
    - increments token_version
    - invalidates existing JWT sessions
    - consumes the reset token
    """

    try:
        user = reset_user_password(
            db,
            raw_token=token,
            new_password=new_password,
        )

    except ValueError as exc:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=str(exc),
        ) from exc

    if user is None:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Invalid or expired password reset token.",
        )

    return {
        "message": (
            "Password reset successfully. "
            "You may now log in with your new password."
        ),
    }