"""
TRACKIT Match Schemas.

Pydantic schemas used by the matching API.

Security principles:

- Match ownership is never supplied by the client.
- User identity comes from the authenticated JWT.
- Match scoring fields are generated by the matching service.
- Clients cannot create or modify match scoring information directly.
- Match responses expose the scoring breakdown and explanation needed
  by clients to understand a potential LOST/FOUND match.
"""

from datetime import datetime
from typing import Literal

from pydantic import BaseModel, ConfigDict


# ============================================================================
# MATCH LEVEL
# ============================================================================

MatchLevel = Literal[
    "none",
    "possible",
    "strong",
]


# ============================================================================
# MATCH RESPONSE
# ============================================================================


class MatchResponse(BaseModel):
    """
    API representation of a potential LOST/FOUND match.

    Match records are generated and maintained by the matching service.
    Clients receive the calculated score, scoring breakdown, match level,
    explanation, and dismissal state.
    """

    model_config = ConfigDict(
        from_attributes=True,
    )

    id: int

    lost_item_id: int
    found_item_id: int

    score: int
    match_level: MatchLevel

    category_score: int
    title_score: int
    description_score: int
    location_score: int
    time_score: int

    reason: str

    is_dismissed: bool

    created_at: datetime
    updated_at: datetime