"""
TRACKIT Comment Database Model.

Represents a user comment attached to a TRACKIT item.

Security principles:
- user_id must reference an existing user.
- item_id must reference an existing item.
- User and item deletion cascade to their comments.
- Comment content is plain untrusted text.
- Empty and whitespace-only comments are rejected at the
  database level.
- Comment length is bounded at the database level.
- Timestamps are generated by the database.
"""

from datetime import datetime

from sqlalchemy import (
    CheckConstraint,
    DateTime,
    ForeignKey,
    Index,
    Text,
    func,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.base import Base


class Comment(Base):
    """
    TRACKIT item comment.

    A comment belongs to exactly one user and one item.

    Security-sensitive ownership is controlled by the service layer;
    the client must never be trusted to choose the comment author.
    """

    __tablename__ = "comments"

    # ========================================================================
    # Primary Key
    # ========================================================================

    id: Mapped[int] = mapped_column(
        primary_key=True,
        index=True,
    )

    # ========================================================================
    # Item
    # ========================================================================

    item_id: Mapped[int] = mapped_column(
        ForeignKey(
            "items.id",
            ondelete="CASCADE",
        ),
        nullable=False,
        index=True,
    )

    # ========================================================================
    # Comment Author
    # ========================================================================

    user_id: Mapped[int] = mapped_column(
        ForeignKey(
            "users.id",
            ondelete="CASCADE",
        ),
        nullable=False,
        index=True,
    )

    # ========================================================================
    # Content
    # ========================================================================

    content: Mapped[str] = mapped_column(
        Text,
        nullable=False,
    )

    # ========================================================================
    # Timestamps
    # ========================================================================

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
    )

    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False,
    )

    # ========================================================================
    # Relationships
    # ========================================================================

    item = relationship(
        "Item",
        back_populates="comments",
    )

    user = relationship(
        "User",
        back_populates="comments",
    )

    # ========================================================================
    # Database Integrity Constraints
    # ========================================================================

    __table_args__ = (
        CheckConstraint(
            "char_length(trim(content)) > 0",
            name="ck_comments_content_not_blank",
        ),
        CheckConstraint(
            "char_length(content) <= 2000",
            name="ck_comments_content_max_length",
        ),
        Index(
            "ix_comments_item_created_at",
            "item_id",
            "created_at",
        ),
    )